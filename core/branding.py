DEFAULT_ORG_NAME = 'شركة نفط الوسط'


def org_name():
    """اسمُ الشركة كما يُطبع: المضبوطُ في الإعدادات، وإلّا الافتراضيّ."""
    from core.models import EmailSettings

    return EmailSettings.get().org_name.strip() or DEFAULT_ORG_NAME
