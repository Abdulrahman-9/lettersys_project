"""علَمُ «التدهور الصامت» لكلّ خيط — يرفعه كلُّ موضعٍ يبتلع عطلاً فيُعيد قيمةً «ناجحة» أفقرَ
ممّا كان سيُعيده لولا العطل (صناديقُ كاشفٍ فارغة، تصعيدُ Tesseract فشل فبقيت التمريرةُ الأولى).

**لماذا:** المسارُ المتسلسل لا يقرؤه — سلوكُه كما هو حرفاً. يقرؤه **الممرُّ المتوازي** وحده
(`core/extraction/lanes.py`): قيمةٌ تدهورت داخل ممرٍّ لا تُستهلك، بل يُعاد حسابُها على خيط
الاستخراج كما يفعل كودُ اليوم في موضعه. فالضغطُ الذي يضيفه التوازي على الذاكرة لا يصل إلى
حقلٍ واحد: الممرُّ إمّا يُعيد ما كان التسلسلُ سيُعيده، وإمّا يُعاد العملُ بالتسلسل.
(مراجعةُ الهويّة العدائيّة 2026‑10‑06: «الفشلُ ⟵ تسلسل» كان أعمى عن الإخفاقات المبتلَعة.)
"""
import threading

_local = threading.local()


def mark(reason: str) -> None:
    """يرفع العلَمَ لهذا الخيط (يبقى آخرُ سبب)."""
    _local.reason = reason


def clear() -> None:
    _local.reason = None


def reason():
    """سببُ التدهور في هذا الخيط منذ آخر `clear()`، أو None."""
    return getattr(_local, 'reason', None)
