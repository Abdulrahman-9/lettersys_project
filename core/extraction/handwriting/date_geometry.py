"""هندسةُ قصاصة التاريخ — **مصدرٌ وحيد** يشترك فيه الإنتاج وسكربتات الحصاد.

الدرسُ الذي يفرض هذه الوحدة مدفوعُ الثمن مرّتين في جبهة العدد: حشوُ الحصاد
وحشوُ الإنتاج عاشا في ملفّين فانزلقا، فصار النموذج يُدرَّب على توزيعٍ ويُستدعى
على آخر (51.5% مقابل 66.5% مطابقةً تامّة — كلفةُ الانزلاق وحدَه). القاعدة
المُستخلَصة: **القارئ لا يُطعَم إلا قصاصةً بهندسة تدريبه حرفيّاً**، وأضمنُ
سبيلٍ لذلك دالّةٌ واحدة يستدعيها الطرفان لا ثابتٌ منسوخ.

`x` هي الهندسة المعتمدة ببوّابة عين D1 (2026-08-24، n=100): حبرٌ ظاهرٌ كاملاً
**96%** وتطابقُ وسمٍ **97.9%**، مقابل 86% للهندسة الوسطى التي سبقتها. ثمنُها
المقيَّد: 13% من القصاصات يدخلها تاريخُ ختمِنا (يصطاده حارسُ الفارق في الواجهة).
"""
from typing import Optional, Sequence, Tuple

# (تمدّدٌ أفقيّ ×عرض الصندوق، بدءٌ رأسيّ، نهايةٌ رأسيّة ×ارتفاع الصندوق)
# البدءُ سالبٌ عمداً: سطرُ التاريخ يُكتب ملاصقاً لأسفل العدد، وبدءُ +0.1 كان
# يحلق رؤوس أرقامه (9 حالاتٍ من 100 في بوّابة العين).
DATE_CROP_GEOM: Tuple[float, float, float] = (2.0, -0.2, 2.4)
GEOMETRY_TAG = 'x1'          # يُلتقَط مع الذهب: بأيّ هندسةٍ قُصَّ هذا الزوج

_MIN_W, _MIN_H = 20, 10


def crop_below_box(img, box: Optional[Sequence[float]]):
    """قصاصةُ ما تحت صندوق العدد بهندسة `x` — تُعاد صورةُ PIL أو None.

    `box` مُطبَّعٌ [x0,y0,x1,y1] على الصفحة الكاملة، و`img` الرسمُ نفسه الذي
    اشتُقّ منه الصندوق (وإلّا فالمقاسُ المرجعيّ مختلفٌ — فخّ 1600/2600/3500).
    """
    if not box or img is None:
        return None
    ext, top, bot = DATE_CROP_GEOM
    W, H = img.width, img.height
    x0, y0, x1, y1 = box
    bw, bh = (x1 - x0), (y1 - y0)
    px0 = max(0, int((x0 - ext * bw) * W))
    px1 = min(W, int((x1 + ext * bw) * W))
    py0 = max(0, int((y1 + top * bh) * H))
    py1 = min(H, int((y1 + bot * bh) * H))
    if (px1 - px0) < _MIN_W or (py1 - py0) < _MIN_H:
        return None
    return img.crop((px0, py0, px1, py1))
