"""المطابقةُ الصارمةُ لمرجعٍ مطبوع — بابُ «النصّ يكفي، فتخطَّ البصريّ».

**لماذا نحويٌّ على المخرَج لا مصنِّفُ نوع** (استشارة فيبل 2026-08-27): جرّبتُ
تمييزَ «الرقميّ الأصيل» بتغطية الصورة فسقط — **كلُّ مستنداتنا ممسوحة**، حتّى
إيميلات NK/ADO/EBS، فطبقةُ نصّها ناتجُ OCR الماسحة لا حروفٌ أصيلة (ومن هنا
`llK-20260257`). وأيُّ مصنِّفٍ بديلٍ سيسقط مثلَه. فالمسارُ النصّيّ يُشغَّل
**دائماً** (0.03 ث)، والمميِّزُ هو **صرامةُ مطابقته**.

**الأرقام التي سوّغت هذا** (e2e-E المختومة، 34 مستنداً حقيقتُها محكَّمةٌ بالعين):
النصُّ 25 إصابة/2 خاطئ بـ0.094 ث مقابل البصريّ 11/2 بـ3.92 ث — **أبطأُ 42 ضعفاً
وأقلُّ إصابةً بأكثر من الضعف**.

**والحدُّ الذي يحرس التعميم**: على المجموعة الرقميّة الأخرى (e2e-D، 60 مستنداً)
يعطي النصُّ الخامُّ صفر إصابةٍ و57 صمتاً بينما البصريُّ 85% — فـ«النصّ أوّلاً» بلا
شرطٍ كارثيّ. ولذلك تُطلق هذه الدالّة على e2e-D **مرّةً واحدةً بالضبط** (الكتاب
11183، وقيمتُها مطابقةٌ للوسم وللمطبوع بالعين)، وذاك فحصُ عدم التراجع في سطر:
**خاطئ = 0 وسقفُ إطلاقٍ ≤ 2**.

**والخطأُ يصير صمتاً لا تحسيناً**: ما لا يجتاز الصرامةَ يُترك للمسار البصريّ —
«الخطأُ المكتوب أسوأ من الفراغ».

**شكلُ الإصدار: الخانات وحدها** — بلاغُ المالك (2026-08-30) أنّ الكاتب **يُسقط
البادئةَ عمداً**، والقاعدة تؤكّده: 12 وسماً ببادئة من 235 عبر الجهات الثلاث (5%)،
وADO وحدَها **88 عارياً مقابل 2**. فيُقنَّن المرجعُ إلى خاناته عبر
`canonical_sender_number()`، ويُحفظ المطبوعُ خامّاً للأثر. وهذا يوحّد المخرَجَ مع
المسار البصريّ (يقرأ خاناتٍ فقط) فتصير مقارنةُ المسارين مطابقةَ سلاسلَ ساذجة.

## الجذرُ الذي كشفه التشخيص (2026-08-30) — ولماذا صار الحكمُ على **السطر**

النسخةُ الأولى اشترطت أن تلاصق المرساةُ قيمتَها. وقياسٌ على النصّ الخامّ أثبت أنّ
هذا يكسر النماذجَ **ذاتَ العمودين**: طبقةُ نصّ الماسحة تُخرج عمودَ القيم كتلةً
وعمودَ التسميات كتلةً أخرى، فتفترق «`No:`» عن «`ADO-507`» بعشرات الأسطر.

| الكتاب | ما يقوله النصّ | ما كان يحدث |
|---|---|---|
| 11125 | `ADO-432` سطراً وحدَه، والمرساةُ `No:` في عمودٍ آخر | التُقطت إحالةُ متنٍ `(Ref No.ADO-403)` |
| 13134 | `ADO-507` سطراً وحدَه | التُقط رقمُ عقدٍ `Contract No.ADo-25-Sc-019` ⟵ `25` |
| 6596 | `Ref: NK-2025 144` — فراغُ ماسحةٍ **داخل** الأرقام | بُترت إلى `NK-2025` فرُفضت صمتاً |

فالعلّةُ لم تكن المرساةَ ولا المنطقةَ الرأسيّة ولا حارزَ التمام، بل **تكوينَ
مجموعة المرشَّحين**: ضيّقةٌ من جهةٍ (تُسقط عمودَ القيم) وسائبةٌ من جهةٍ (تقبل
إحالةَ نثرٍ ورقمَ عقد). والحدسُ الذي حلّها ومقيسٌ: **المرجعُ المطبوع يسكن حقلَ
نموذجٍ يستغرق سطرَه، والإحالةُ الكاذبة تسكن جملةَ نثر**.

**الأثرُ المقيس** (نفسُ المجموعتين، تشغيلةٌ واحدة): إصابة **25 ⟵ 32** وخاطئ
**2 ⟵ 0**، وe2e-D **بلا أيّ تغيير** (إطلاقةٌ واحدةٌ صحيحة). وصفرُ تراجعٍ صفّاً
بصفّ — لا مستندَ واحدٌ يصيبه القديمُ وتُخطئه القاعدة.

**وتفكيكُ البنود يقول أيّها يحمل الوزن**: إسقاطُ طبقة «القيمةُ تستغرق سطرَها»
يهبط بالإطلاق 32 ⟵ 26؛ وإسقاطُ حدَّي المرساة **معاً** يُعيد الخطأين بعينهما
(11125 ⟵ `403` و13134 ⟵ `25`). أمّا ضمُّ فراغ OCR وحارسُ الفاصل المختلط فصفرُ
أثرٍ على هذه العيّنة — ويبقيان لأنّ علّتَهما مرئيّةٌ في النصّ الخامّ (6596)
والتخلّي عنهما يشتري لا شيء.

**والمنطقةُ الرأسيّة تبقى شرطاً**: توسيعُها إلى كلّ الصفحة الأولى يضيف ستّ
إطلاقاتٍ صحيحة، لكنّ **خمساً منها تُصدَّق بعمود الوسم لا بالعين** — فتنتظر
تحكيمَ عينٍ على مجموعةٍ جديدة قبل أن تُعتمد.
"""
import datetime
import re
from typing import Optional

# ── قائمةُ البادئات المعتمدة — **مكانٌ واحد** (درس `numbering.py`) ──────────
# جهةٌ جديدة تصمت حتّى تُضاف: صمتٌ لا خطأ.
APPROVED_PREFIXES = (
    'NK',
    'ADO',
    'EBS-MDOC',
)

_YEAR_MIN = 2020
_HEAD_FRACTION = 0.35          # المنطقةُ الرأسيّة: أعلى ثلث نصّ الصفحة الأولى
_HEAD_MIN_CHARS = 400
_LOOKAHEAD_LINES = 2           # مرساةٌ وحدَها ⟵ كم سطراً بعدها نفتّش
_PURITY = 8                    # أقصى بقيّةٍ في السطر بعد القيمة (سطرُ حقلٍ لا نثر)
_PRE_ANCHOR_MAX = 12           # أقصى ما يسبق المرساةَ في سطرها
_TAIL_MAX = 3                  # أقصى ما يلي القيمةَ في سطرٍ مُرسّى

# البادئةُ تعرّف نفسَها؛ والفاصلُ يسمح بشُرطةٍ ساقطةٍ (`ADO627`) وبفراغِ تقطيعٍ
# (`EBS- MdOC-…`)؛ والأرقامُ تسمح بمجموعةٍ ثانيةٍ بعد فراغِ ماسحةٍ (`NK-2025 144`).
_PREFIX = r'(?:EBS[-\s]*MdOC|NK|ADO)'
_SEP = r'(?:[-\s]{0,3}|,[ ]?)'
_DIGITS = r'\d{2,12}(?:[ ]\d{1,4})?'
_VALUE_RE = re.compile(_PREFIX + _SEP + _DIGITS, re.IGNORECASE)

# مرساةٌ تسبق القيمةَ في سطرها. «No» بلا حدِّ كلمةٍ كانت تلتقط جوفَ الكلمات.
_ANCHOR_WORDS = r'(?:ref\.?(?:\s*no\.?)?|reference|\bno\.?|العدد)'
_ANCHOR_TAIL_RE = re.compile(_ANCHOR_WORDS + r'\s*[:：.,#\-]{0,2}\s*$', re.IGNORECASE)
_ANCHOR_ALONE_RE = re.compile(r'^\s*' + _ANCHOR_WORDS + r'\s*[:：.,#\-]{0,2}\s*$',
                              re.IGNORECASE)


def digits_of(value: str) -> str:
    """خاناتُ القيمة وحدَها — أساسُ كلّ مقارنةٍ ومطابقة."""
    return ''.join(c for c in str(value or '') if c.isdigit())


def canonical_sender_number(raw: str) -> str:
    """**دالّةُ التقنين الوحيدة**: المرجعُ المطبوع ⟵ ما يكتبه الكاتب فعلاً.

    تُستعمل في الإصدار والحارس والتصادق معاً — درسُ `numbering.py`: قاعدةُ شكلٍ
    في أحد عشر موضعاً تنجرف. وهي لعدد **الجهة** وحدَه ولا تمسّ `our_number`.
    """
    return digits_of(raw)


def _prefix_of(value: str) -> str:
    m = re.match(r'([A-Za-z][A-Za-z\-]*)', value or '')
    return (m.group(1) if m else '').upper().rstrip('-')


def _separator_is_clean(value: str) -> bool:
    """الفاصلُ شُرَطٌ/فراغٌ **أو** فاصلةٌ واحدة — لا خليط.

    `ADO,118` قراءةٌ سليمةٌ لماسحةٍ أسقطت الشرطة؛ أمّا `ADO-,103` فخليطٌ يدلّ على
    قراءةٍ ممسوخة (الكتاب 11108: الوسمُ 403 لا 103).
    """
    m = re.match(r'^(?:EBS[-\s]*MdOC|NK|ADO)([^0-9]*)', value or '', re.IGNORECASE)
    sep = m.group(1) if m else ''
    return not (',' in sep and re.search(r'[-.]', sep))


def _compact(value: str) -> str:
    """يضمّ فراغَ الماسحة داخل الأرقام: `NK-2025 144` ⟵ `NK-2025144`.

    الضمُّ **مشروط**: المجموعةُ الأولى سنةٌ (`20\\d{2}`) والثانيةُ 2–4 خانات —
    وإلّا فالفراغُ فاصلُ حقلٍ لا تقطيعَ قراءةٍ، فتُؤخذ المجموعةُ الأولى وحدَها.
    """
    value = (value or '').strip()
    m = re.search(r'(\d[\d ]*\d|\d)$', value)
    if not m:
        return re.sub(r'\s+', '', value)
    head, tail = value[:m.start()], m.group(1)
    groups = tail.split()
    if len(groups) > 1:
        joined = ''.join(groups[1:])
        tail = (''.join(groups) if (re.fullmatch(r'20\d{2}', groups[0])
                                    and 2 <= len(joined) <= 4)
                else groups[0])
    return re.sub(r'\s+', '', head) + tail


def _passes_strictness(candidate: str) -> bool:
    """شروطُ الصرامة على المرشَّح المُقنَّن — لا يُخفَّف واحدٌ منها منفرداً."""
    if _prefix_of(candidate) not in APPROVED_PREFIXES:
        return False
    if not _separator_is_clean(candidate):
        return False
    digits = digits_of(candidate)
    if not digits:
        return False
    # الشكلُ السنويُّ يُعرَف بصدرِه **وطولِه** معاً. وبلا شرط `19` كان
    # `NK-19990233` يمرّ: صدرُه ليس `20` فيُعامَل رقماً عاديّاً بلا حكمِ مدىً —
    # ثغرةٌ كشفها الحرز، وصفرُ وسمٍ حقيقيٍّ بهذا الشكل (مقيس).
    if re.match(r'^(?:19|20)\d{2}', digits):
        if len(digits) < 7:
            return False                  # سنةٌ عاريةٌ = بترُ طرفِ سطر (13277)
        if len(digits) <= 8:
            return _YEAR_MIN <= int(digits[:4]) <= datetime.date.today().year + 1
        return True
    return len(digits) >= 2


def strict_ref_match(text: str) -> Optional[str]:
    """يُعيد **المرجعَ المطبوع كما هو** إن اجتاز كلّ شروط الصرامة، وإلّا None.

    الإصدارُ يمرّ بـ`canonical_sender_number()`؛ وهذه تُعيد الخامّ ليُحفظ أثراً.

    ثلاثُ طبقاتٍ بأولويّةٍ صارمة، كلُّها **داخل المنطقة الرأسيّة**:
      ١. **مرساةٌ في السطر نفسه** تسبق القيمةَ، بحدَّين: ما قبل المرساة ≤12 حرفاً
         وما بعد القيمة ≤3. الحدّان معاً هما ما يرفض `(Ref No.ADO-403)` وسط جملةٍ
         و`Contract No.ADo-25-Sc-019` — وإسقاطُهما معاً يُعيد الخطأين مقيساً.
      ٢. **مرساةٌ وحدَها على سطر** ⟵ القيمةُ في أوّل سطرٍ غيرِ فارغٍ بعدها
         (نموذجُ ADO: `No.:` ثمّ `ADO-361`).
      ٣. **بلا مرساة**: القيمةُ **تستغرق سطرَها** (بقيّةٌ ≤ حرفين) — وهذا ما
         يُنقذ عمودَ القيم في النماذج ذات العمودين، وهو أكبرُ بندٍ وزناً.
    """
    if not text:
        return None
    head = text[:max(_HEAD_MIN_CHARS, int(len(text) * _HEAD_FRACTION))]
    lines = head.split('\n')
    anchored, standalone = [], []

    for i, raw_line in enumerate(lines):
        line = raw_line.strip()

        if _ANCHOR_ALONE_RE.match(line):          # ── الطبقة ٢
            for j in range(i + 1, min(i + 1 + _LOOKAHEAD_LINES, len(lines))):
                nxt = lines[j].strip()
                if not nxt:
                    continue
                m = _VALUE_RE.search(nxt)
                if m and len(nxt) - len(m.group(0)) <= _PURITY:
                    anchored.append(_compact(m.group(0)))
                break                              # أوّلُ سطرٍ غيرِ فارغٍ يحسم
            continue

        for m in _VALUE_RE.finditer(line):
            before = line[:m.start()]
            residual = len(line) - len(m.group(0))
            if (_ANCHOR_TAIL_RE.search(before)     # ── الطبقة ١
                    and len(before.strip()) <= _PRE_ANCHOR_MAX
                    and residual <= _PURITY + len(before.strip())
                    and len(line) - m.end() <= _TAIL_MAX):
                anchored.append(_compact(m.group(0)))
            elif residual <= 2:                    # ── الطبقة ٣
                standalone.append(_compact(m.group(0)))

    for candidate in anchored + standalone:
        if _passes_strictness(candidate):
            return candidate
    return None
