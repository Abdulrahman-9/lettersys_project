# -*- coding: utf-8 -*-
"""هل الملفُّ المسجَّل موجودٌ فعلاً في التخزين؟ — مصدرٌ واحدٌ لقالب تفاصيل الكتاب وسلسلة معاينته.

``FieldFile.size`` يسأل التخزين، فإن غاب الملفّ (نسخةُ قاعدةٍ بلا مجلّد media، أو ملفٌّ حُذف يدويّاً)
رفع ``FileNotFoundError`` وأسقط تفاصيلَ الكتاب كلَّها بـ500 — لأجل سطرٍ يعرض الحجم. والعارضُ كان
يفتح الملفَّ الغائب فيرسم مربّعاً بأيقونة ملفٍّ مكسور.
"""


def stored_size(field):
    """حجمُ الملفّ بالبايت، أو ``None`` إن لم يكن للحقل ملفّ أو غاب عن التخزين."""
    if not field:
        return None
    try:
        return field.size
    except (OSError, ValueError):
        return None
