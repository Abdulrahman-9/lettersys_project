# -*- coding: utf-8 -*-
"""قفلُ PyMuPDF الواحد للعمليّة — كلُّ فتحٍ ورسمٍ وكتابةٍ لملفّ PDF في الخادم يمرّ به.

**لماذا:** سياقُ MuPDF في هذه النسخة **وحيدُ الخيط وبلا قفلٍ داخليّ**
(`pymupdf/__init__.py`: `reinit_singlethreaded()`). صحيحٌ أنّ نداءاته تمسك الـGIL عند الدخول،
لكنّها تُفلتها في منتصف النداء حين ترتدّ أخطاءُ MuPDF إلى بايثون فتطبع (`JM_mupdf_show_errors`)
— فيدخل خيطٌ آخر السياقَ نفسَه في منتصف عمليّة. ومعاينةُ الصفحة وحذفُ الفراغات والاستخراجُ
تجري في خيوط طلباتٍ مختلفة معاً (مراجعةُ الخيوط والذاكرة 2026‑10‑06). القفلُ يُسلسلها كلَّها؛
وكلُّ رسمٍ هنا عشراتُ الميلّي ثانية لصفحةٍ واحدة، فالانتظارُ قصير.

قفلٌ قابلٌ لإعادة الدخول (RLock): دالّةٌ تحت القفل تنادي أخرى تأخذه لا تتجمّد. ولا يُمسَك
أبداً أثناء انتظار Tesseract أو ONNX أو استخراجٍ كامل — الرسمُ وفتحُ الملفّ وحفظُه وحدها تحته.
"""
import functools
import threading

MUPDF_LOCK = threading.RLock()


def mupdf_locked(fn):
    """يُشغّل الدالّةَ كلَّها تحت `MUPDF_LOCK` — لدوالّ بدنُها PyMuPDF وحده (معاينةٌ، عدُّ صفحات)."""
    @functools.wraps(fn)
    def wrapper(*args, **kwargs):
        with MUPDF_LOCK:
            return fn(*args, **kwargs)
    return wrapper
