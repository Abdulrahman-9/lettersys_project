"""
نطاق رؤية الكتب — **المصدر الوحيد** لقاعدة «من يرى ماذا».

كانت القاعدة منسوخة يدويّاً في سبعةٍ وعشرين موضعاً بشكلين:

* ``request.user.is_superuser or request.user.is_staff`` — إداريّ فقط.
* ``... or book.created_by == request.user`` — إداريّ أو مالك الكتاب.

قاعدةٌ بهذا الانتشار لا تُغيَّر: كلّ نسخةٍ منسيّة تصير ثغرةً أو تراجعاً. والمرحلة
«أ» من خطّة التعميم ستستبدل «المالك» بـ«القسم» — وهي مستحيلةٌ عمليّاً وسبعٌ
وعشرون نسخةً في الطريق.

مثالُ التكلفة (مقيس): وحدة البريد وحدها كانت اثني عشر موضعاً بلا نطاق، لأنّ
كتابة القاعدة في كلّ مرّة أسهل من تذكّر أنّها موجودة.

**العقد الحالي:** الإداريّ (superuser أو staff) يرى كلّ شيء، وغيره يرى ما أنشأه.
ملاحظة مقصودة: ``is_staff`` تُوسّع الرؤية ضمناً (``core/roles.py`` يمنح حاملها
دور «مُدخِل»)، وهو سلوكٌ قائم أُبقي كما هو في هذه الدفعة — فصلُ الصفة الإداريّة
عن نطاق البيانات قرارُ مالكٍ مؤجَّل إلى المرحلة أ.

**التطوّر المرتقب:** حين يصل بُعد القسم، تتغيّر ``scope_books_for`` وحدها.
"""


def is_privileged(user) -> bool:
    """أهذا مستخدمٌ إداريّ يرى بيانات الجميع؟"""
    return bool(user.is_superuser or user.is_staff)


def can_view_book(book, user) -> bool:
    """أيحقّ للمستخدم الاطّلاع على هذا الكتاب (أو التصرّف به)؟"""
    return bool(is_privileged(user) or book.created_by_id == user.id)


def scope_books_for(user, qs=None):
    """الكتب المرئيّة للمستخدم — صيغة الـqueryset.

    تُفضَّل على ``can_view_book`` حيثما أمكن: النطاق داخل الاستعلام يجعل
    كتابَ غيرك «غير موجود» لا «ممنوع»، فلا يُسرَّب وجودُه من فرق الرمزين.
    """
    if qs is None:
        from core.models import Book
        qs = Book.objects.all()
    if is_privileged(user):
        return qs
    return qs.filter(created_by=user)
